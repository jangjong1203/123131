-- ==========================================
-- 📝 방명록(Guestbook) Supabase 테이블 생성 스크립트
-- ==========================================
-- Supabase 대시보드 > SQL Editor 메뉴에 붙여넣고 [Run]을 누르세요.

-- 1. guestbook 테이블 생성
CREATE TABLE IF NOT EXISTS public.guestbook (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  message TEXT NOT NULL,
  likes INTEGER DEFAULT 0 NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. 행 단위 보안(Row Level Security, RLS) 활성화
ALTER TABLE public.guestbook ENABLE ROW LEVEL SECURITY;

-- 3. 익명(anon) 사용자 정책 설정
-- 3-1. 방명록 조회 허용 (모든 방문자)
CREATE POLICY "누구나 방명록 조회 가능"
  ON public.guestbook
  FOR SELECT
  USING (true);

-- 3-2. 방명록 작성 허용 (모든 방문자)
CREATE POLICY "누구나 방명록 작성 가능"
  ON public.guestbook
  FOR INSERT
  WITH CHECK (true);

-- 3-3. 좋아요 수 증가 등 수정 허용
CREATE POLICY "누구나 좋아요 수정 가능"
  ON public.guestbook
  FOR UPDATE
  USING (true);

-- 3-4. 방명록 글 삭제 허용
CREATE POLICY "누구나 방명록 삭제 가능"
  ON public.guestbook
  FOR DELETE
  USING (true);

-- 4. 실시간(Realtime) 동기화 활성화 (선택 사항)
-- 다른 사용자가 글을 남기면 새로고침 없이 화면에 즉시 나타납니다.
ALTER PUBLICATION supabase_realtime ADD TABLE public.guestbook;
